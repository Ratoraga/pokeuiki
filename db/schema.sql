-- Usuários
CREATE TABLE IF NOT EXISTS users (
  id            SERIAL PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  email         VARCHAR(255) NOT NULL UNIQUE,
  password_hash TEXT         NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Catálogo de Pokémon (preenchido pelo import da PokeAPI)
CREATE TABLE IF NOT EXISTS pokemon (
  id    INTEGER     PRIMARY KEY,
  name  VARCHAR(50) NOT NULL UNIQUE,
  type1 VARCHAR(20) NOT NULL,
  type2 VARCHAR(20)
);

ALTER TABLE pokemon
  ADD COLUMN IF NOT EXISTS base_hp  INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS base_atk INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS base_def INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS base_spa INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS base_spd INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS base_spe INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS species_id INTEGER,
  ADD COLUMN IF NOT EXISTS can_evolve BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS abilities (
  id   INTEGER      PRIMARY KEY,
  name VARCHAR(80)  NOT NULL
);

CREATE TABLE IF NOT EXISTS items (
  id   INTEGER      PRIMARY KEY,
  name VARCHAR(80)  NOT NULL
);

CREATE TABLE IF NOT EXISTS moves (
  id           INTEGER     PRIMARY KEY,
  name         VARCHAR(80) NOT NULL,
  type         VARCHAR(20) NOT NULL,
  damage_class VARCHAR(10) NOT NULL,
  power        INTEGER,
  accuracy     INTEGER,
  pp           INTEGER
);

ALTER TABLE moves
  ADD COLUMN IF NOT EXISTS priority       INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS target         VARCHAR(40),
  ADD COLUMN IF NOT EXISTS category       VARCHAR(30),
  ADD COLUMN IF NOT EXISTS ailment        VARCHAR(30),
  ADD COLUMN IF NOT EXISTS ailment_chance INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS stat_chance    INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS stat_changes   TEXT    NOT NULL DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS drain          INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS healing        INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS flinch_chance  INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS crit_rate      INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS min_hits       INTEGER,
  ADD COLUMN IF NOT EXISTS max_hits       INTEGER;

CREATE TABLE IF NOT EXISTS pokemon_abilities (
  pokemon_id INTEGER NOT NULL REFERENCES pokemon(id) ON DELETE CASCADE,
  ability_id INTEGER NOT NULL REFERENCES abilities(id),
  is_hidden  BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (pokemon_id, ability_id)
);

CREATE TABLE IF NOT EXISTS pokemon_moves (
  pokemon_id INTEGER NOT NULL REFERENCES pokemon(id) ON DELETE CASCADE,
  move_id    INTEGER NOT NULL REFERENCES moves(id),
  PRIMARY KEY (pokemon_id, move_id)
);

-- Só guarda o que NÃO é 1x (ausente = dano normal)
CREATE TABLE IF NOT EXISTS type_effectiveness (
  attacker   VARCHAR(20)  NOT NULL,
  defender   VARCHAR(20)  NOT NULL,
  multiplier NUMERIC(3,2) NOT NULL,
  PRIMARY KEY (attacker, defender)
);

-- Times
CREATE TABLE IF NOT EXISTS teams (
  id          SERIAL PRIMARY KEY,
  user_id     INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        VARCHAR(100) NOT NULL,
  description TEXT,
  is_public   BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  UNIQUE (user_id, name)
);

CREATE INDEX IF NOT EXISTS idx_teams_user_id ON teams(user_id);

CREATE TABLE IF NOT EXISTS team_pokemon (
  id         SERIAL PRIMARY KEY,
  team_id    INTEGER  NOT NULL REFERENCES teams(id)   ON DELETE CASCADE,
  pokemon_id INTEGER  NOT NULL REFERENCES pokemon(id),
  slot       SMALLINT NOT NULL CHECK (slot BETWEEN 1 AND 6),
  nickname   VARCHAR(50),
  UNIQUE (team_id, slot),
  UNIQUE (team_id, pokemon_id)
);

